/// Spacing, radii and control sizes from the design system.
abstract final class AppSpacing {
  static const double xs = 4;
  static const double sm = 8;
  static const double md = 12;
  static const double lg = 16;
  static const double xl = 24;

  /// Side gutter of every screen.
  static const double gutter = 16;
}

abstract final class AppRadius {
  static const double sm = 12;
  static const double md = 14;
  static const double lg = 16;
  static const double xl = 20;
  static const double card = 22;
  static const double sheet = 24;
  static const double pill = 999;
}

abstract final class AppSizes {
  /// Minimum tap target.
  static const double iconControl = 48;
  static const double field = 52;
  static const double button = 54;
  static const double primaryButton = 56;
  static const double listRow = 64;
}
